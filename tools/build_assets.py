#!/usr/bin/env python3
"""Draw the Soundboard's icons, in the Offline Toolkit style.

- assets/icon.png / .ico / .icns: the toolkit's purple-blue tile with a white "sound bars" glyph.
- The window/header icons and the few Lucide icons the shared UI block doesn't have
  (mic, headphones, keyboard, layout-grid, square), written into soundboard.py between
  the "generated by tools/build_assets.py" markers.

The tile background is taken from a sibling toolkit app (../audio-converter), with its
glyph painted out, so every app's tile matches exactly. Run from the repo root:
    python tools/build_assets.py
"""
import base64
import io
import os
import re
import sys

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIBLING = os.path.join(os.path.dirname(ROOT), "audio-converter")
APP = os.path.join(ROOT, "soundboard.py")

# The shared block's icon colors (see ui_icon): "" is purple.
COLORS = {"": (103, 57, 223), "white": (255, 255, 255), "dark": (49, 25, 95), "grey": (153, 145, 180),
           "pink": (211, 57, 84)}


def erase_glyph(img):
    """The tile without its white glyph: each glyph pixel is filled in from the background
    to its left and right on the same row."""
    a = np.array(img.convert("RGBA")).astype(float)
    rgb, alpha = a[:, :, :3], a[:, :, 3]
    lo = rgb.min(axis=2)
    glyph = (lo > 120) & (alpha > 0)  # whitish (the tile itself is dark, saturated)
    for _ in range(max(3, img.width // 14)):  # and its soft edge and drop shadow
        g = glyph.copy()
        g[1:] |= glyph[:-1]; g[:-1] |= glyph[1:]; g[:, 1:] |= glyph[:, :-1]; g[:, :-1] |= glyph[:, 1:]
        glyph = g
    glyph &= alpha > 250
    out = rgb.copy()
    for y in range(img.height):
        row = glyph[y]
        if not row.any():
            continue
        good = np.nonzero(~row & (alpha[y] > 250))[0]
        if len(good) < 2:
            continue
        bad = np.nonzero(row)[0]
        for c in range(3):
            out[y, bad, c] = np.interp(bad, good, rgb[y, good, c])
    a[:, :, :3] = out
    return Image.fromarray(a.astype(np.uint8), "RGBA")


def sound_bars(size, box):
    """White rounded bars (a sound wave), drawn 8x larger then shrunk for smooth edges."""
    k = 8
    layer = Image.new("RGBA", (size * k, size * k), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    x0, y0, x1, y1 = [v * k for v in box]
    heights = [0.34, 0.66, 1.0, 0.66, 0.34]
    n = len(heights)
    w = (x1 - x0) / (n + (n - 1) * 0.75)
    gap = w * 0.75
    cy = (y0 + y1) / 2
    for i, h in enumerate(heights):
        x = x0 + i * (w + gap)
        half = max(w / 2, (y1 - y0) * h / 2)
        d.rounded_rectangle((x, cy - half, x + w, cy + half), radius=w / 2, fill=(255, 255, 255, 255))
    return layer.resize((size, size), Image.LANCZOS)


def with_glyph(tile):
    t = erase_glyph(tile)
    bbox = t.getchannel("A").getbbox()
    bw, bh = bbox[2] - bbox[0], bbox[3] - bbox[1]
    m = 0.25
    box = (bbox[0] + bw * m, bbox[1] + bh * m, bbox[2] - bw * m, bbox[3] - bh * m)
    t.alpha_composite(sound_bars(t.width, box))
    return t


# ---- Lucide icons (ISC license), drawn from their 24x24 SVG geometry --------- #
def lucide(name, size, color):
    k = 16
    s = size * k / 24  # one SVG unit
    sw = 2 * s  # stroke width 2
    img = Image.new("RGBA", (size * k, size * k), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    col = COLORS[color] + (255,)

    def P(x, y):
        return x * s, y * s

    def line(*pts):
        pts = [P(*p) for p in pts]
        d.line(pts, fill=col, width=round(sw), joint="curve")
        for x, y in (pts[0], pts[-1]):  # round caps
            d.ellipse((x - sw / 2, y - sw / 2, x + sw / 2, y + sw / 2), fill=col)

    def dot(x, y):
        x, y = P(x, y)
        d.ellipse((x - sw / 2, y - sw / 2, x + sw / 2, y + sw / 2), fill=col)

    def rrect(x, y, w, h, r, fill=False):
        box = (*P(x - 1, y - 1), *P(x + w + 1, y + h + 1))  # outer edge of the stroke
        if fill:
            d.rounded_rectangle(box, radius=(r + 1) * s, fill=col)
        else:
            d.rounded_rectangle(box, radius=(r + 1) * s, outline=col, width=round(sw))

    def arc(cx, cy, r, a0, a1):
        d.arc((*P(cx - r - 1, cy - r - 1), *P(cx + r + 1, cy + r + 1)), a0, a1, fill=col, width=round(sw))

    if name == "mic":
        rrect(9, 2, 6, 13, 3)
        arc(12, 12, 7, 0, 180)
        line((19, 10), (19, 12))
        line((5, 10), (5, 12))
        line((12, 19), (12, 22))
    elif name == "headphones":
        arc(12, 12, 9, 180, 360)
        line((3, 12), (3, 19))
        line((21, 12), (21, 19))
        rrect(3, 14, 5, 7, 2)
        rrect(16, 14, 5, 7, 2)
    elif name == "keyboard":
        rrect(2, 4, 20, 16, 2)
        for x, y in ((6, 8), (10, 8), (14, 8), (18, 8), (8, 12), (12, 12), (16, 12)):
            dot(x, y)
        line((7, 16), (17, 16))
    elif name == "layout-grid":
        for x, y in ((3, 3), (14, 3), (14, 14), (3, 14)):
            rrect(x, y, 7, 7, 1)
    elif name == "square-solid":
        rrect(4, 4, 16, 16, 2.5, fill=True)
    elif name == "sticker":  # lucide "sticker"
        line((15.5, 3), (8.5, 3))
        arc(8.5, 8.5, 5.5, 180, 270)
        line((3, 8.5), (3, 15.5))
        arc(8.5, 15.5, 5.5, 90, 180)
        line((8.5, 21), (15.5, 21))
        line((21, 8.5), (21, 15.5))
        arc(15.5, 15.5, 5.5, 0, 90)
        arc(15.5, 8.5, 5.5, 270, 360)
        arc(12, 12, 4.2, 20, 160)
        dot(9, 9.5)
        dot(15, 9.5)
    else:
        raise ValueError(name)
    return img.resize((size, size), Image.LANCZOS)


EXTRA_ICONS = {  # name: color variants
    "mic": ["", "grey"], "headphones": ["", "grey"], "keyboard": ["", "grey"],
    "layout-grid": ["", "white"], "square-solid": ["white", ""], "sticker": ["", "dark"],
}


# Colors of icons the shared block has only in purple.
RECOLOR = {"pencil": ["white", "dark"], "volume-2": ["dark", "grey", "white"], "rotate-cw": ["dark"]}


def recolor(data, color):
    im = Image.open(io.BytesIO(base64.b64decode(data))).convert("RGBA")
    solid = Image.new("RGBA", im.size, COLORS[color] + (255,))
    solid.putalpha(im.getchannel("A"))
    return solid


def b64(img):
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def wrap(name, data, width=96):
    rows = [data[i:i + width] for i in range(0, len(data), width)]
    return f"{name} = (\n" + "\n".join(f'    "{r}"' for r in rows) + "\n)\n"


def main():
    src_icon = os.path.join(SIBLING, "assets", "icon.png")
    src_app = os.path.join(SIBLING, "audio_converter.py")
    if not (os.path.exists(src_icon) and os.path.exists(src_app)):
        sys.exit("Needs the audio-converter repo next to this one (for the shared tile).")
    big = with_glyph(Image.open(src_icon))
    assets = os.path.join(ROOT, "assets")
    big.save(os.path.join(assets, "icon.png"), optimize=True)
    big.save(os.path.join(assets, "icon.ico"), sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    big.resize((1024, 1024), Image.LANCZOS).save(os.path.join(assets, "icon.icns"))

    text = open(src_app, encoding="utf-8").read()
    small = {}
    for name in ("APP_ICON", "HEADER_ICON"):
        m = re.search(name + r" = \((.*?)\n\)", text, re.S)
        data = "".join(re.findall(r'"([^"]*)"', m.group(1)))
        small[name] = b64(with_glyph(Image.open(io.BytesIO(base64.b64decode(data)))))

    icons = {}
    for name, colors in EXTRA_ICONS.items():
        for color in colors:
            for size in (15, 18):
                icons[f"{name}{'-' + color if color else ''}@{size}"] = b64(lucide(name, size, color))

    m = re.search(r"UI_ICONS = \{(.*?)\n\}", text, re.S)
    shared = dict(re.findall(r'"([\w-]+@\d+)":\s*"([^"]+)"', m.group(1)))
    for name, colors in RECOLOR.items():
        for color in colors:
            for size in (15, 18):
                icons[f"{name}-{color}@{size}"] = b64(recolor(shared[f"{name}@{size}"], color))

    block = ("# >>> generated by tools/build_assets.py (do not edit by hand)\n"
             + wrap("APP_ICON", small["APP_ICON"]) + wrap("HEADER_ICON", small["HEADER_ICON"])
             + "EXTRA_ICONS = {\n" + "".join(f'    "{k}": "{v}",\n' for k, v in icons.items()) + "}\n"
             + "# <<< generated by tools/build_assets.py\n")
    app = open(APP, encoding="utf-8").read()
    start, end = "# >>> generated by tools/build_assets.py", "# <<< generated by tools/build_assets.py\n"
    i, j = app.index(start), app.index(end) + len(end)
    open(APP, "w", encoding="utf-8", newline="\n").write(app[:i] + block + app[j:])
    # Previews, to check by eye.
    prev = Image.new("RGBA", (len(icons) * 24 + 8, 30), (255, 255, 255, 255))
    for n, (k, v) in enumerate(icons.items()):
        im = Image.open(io.BytesIO(base64.b64decode(v)))
        bg = (91, 51, 198, 255) if "white" in k else (255, 255, 255, 255)
        cell = Image.new("RGBA", (22, 22), bg)
        cell.alpha_composite(im, ((22 - im.width) // 2, (22 - im.height) // 2))
        prev.alpha_composite(cell, (4 + n * 24, 4))
    if len(sys.argv) > 1:  # a path to save a preview of the icons to
        prev.save(sys.argv[1])
    print("icons written")


if __name__ == "__main__":
    main()
